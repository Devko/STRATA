#!/usr/bin/env python3
"""Rewrite tests/golden_data.inc from a STRATA_GOLDEN=print run of the host suite.

    make -C host build && STRATA_GOLDEN=print build/host/strata-tests > /tmp/g.txt
    python3 tools/golden_update.py /tmp/g.txt

Only after a deliberate sound change, and after listening: tests/test_golden.cpp says why.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
lines = [l[len("GOLDEN "):].rstrip() for l in open(sys.argv[1]) if l.startswith("GOLDEN ")]
if not lines:
    sys.exit("no GOLDEN lines: was the suite run with STRATA_GOLDEN=print?")
names = [l.split('"')[1] for l in lines]
if len(set(names)) != len(names):
    sys.exit("two renders share a name")
with open(os.path.join(ROOT, "tests", "golden_data.inc"), "w") as f:
    f.write("// Generated by tools/golden_update.py from STRATA_GOLDEN=print. Do not edit by hand.\n")
    f.write("// tests/test_golden.cpp says when to regenerate it.\n")
    f.write("const Golden kGolden[] = {\n")
    for l in lines:
        f.write("    " + l + "\n")
    f.write("};\n")
print("%d renders written" % len(lines))
